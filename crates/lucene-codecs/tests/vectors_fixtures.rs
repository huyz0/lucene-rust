//! Differential test against a real `Lucene99HnswVectorsFormat` segment: the
//! `.vec`/`.vemf` flat store and the `.vem`/`.vex` HNSW graph written by an
//! actual `IndexWriter` over 4000 documents and five vector fields (dense
//! FLOAT32, sparse FLOAT32, a sparse field small enough that Lucene skips
//! graph construction, BYTE, and a 5-document field). Regenerate with
//! `fixtures/src/GenVectors.java`.
//!
//! Four independent things are checked, in increasing order of how much they
//! prove:
//!
//! 1. **Metadata**: field numbers, encodings, similarity functions, counts,
//!    and per-level graph shape.
//! 2. **Vectors**: spot ordinals decoded bit-for-bit, and the sampled
//!    ordinal -> doc mapping (dense identity and the sparse
//!    `DirectMonotonicReader` path).
//! 3. **The graph itself**: per level, an order-sensitive hash over every
//!    node's neighbour list. A mis-decoded node offset, a dropped group-vint
//!    group or an off-by-one in the level index offsets all change it.
//! 4. **Search**: our searcher, run over *Lucene's own* graph, must reproduce
//!    Lucene's `KnnFloatVectorQuery` results -- the same doc ids in the same
//!    order, scores within 1e-6 (see `assert_hits_match` for why a tolerance
//!    is the only honest comparison) -- and our exhaustive scan must reproduce
//!    Lucene's brute-force top-k the same way.
//!
//! Then, separately, `rust_built_graph_recall_matches_lucene` builds a graph
//! *here* over the same vectors at the same `M`/`beamWidth`/seed and reports
//! its recall next to Lucene's on the same queries. That is the only number
//! that says the *construction* algorithm (level assignment, diversity rule,
//! entry-point descent) was ported and not merely the file format.
// Test-support code opts out of the arithmetic gate at the file boundary:
// the gate exists for values read off disk in production decode paths, not
// for a fixture builder's own index arithmetic. See
// `docs/arithmetic-gate.md`.
#![allow(clippy::arithmetic_side_effects)]

