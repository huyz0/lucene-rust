//! `com.ibm.icu.impl.coll.CollationFCD`: the coarse lead/trail combining
//! class bit sets the FCD collation iterator checks before it looks a code
//! unit's FCD value up. The four tables are ICU's (generated from the
//! Unicode data by ICU's tools), copied from `CollationFCD.java`.

/// `hasLccc(c)`: `c` (a BMP code unit) may have a non-zero lead combining
/// class.
#[inline]
pub fn has_lccc(c: i32) -> bool {
    c >= 0x300 && bit(&LCCC_INDEX, &LCCC_BITS, c)
}

/// `hasTccc(c)`: `c` may have a non-zero trail combining class.
#[inline]
pub fn has_tccc(c: i32) -> bool {
    c >= 0xc0 && bit(&TCCC_INDEX, &TCCC_BITS, c)
}

/// `mayHaveLccc(c)`: a code point; a supplementary one is checked by its
/// lead surrogate.
pub fn may_have_lccc(c: i32) -> bool {
    if c < 0x300 {
        return false;
    }
    let c = if c > 0xffff {
        crate::icu4j::utf16::surrogates(c).0.into()
    } else {
        c
    };
    bit(&LCCC_INDEX, &LCCC_BITS, c)
}

/// `maybeTibetanCompositeVowel(c)`.
#[inline]
pub fn maybe_tibetan_composite_vowel(c: i32) -> bool {
    c & 0x1f_ff01 == 0xf01
}

/// `isFCD16OfTibetanCompositeVowel(fcd16)`.
#[inline]
pub fn is_fcd16_of_tibetan_composite_vowel(fcd16: i32) -> bool {
    fcd16 == 0x8182 || fcd16 == 0x8184
}

#[inline]
fn bit(index: &[u8; 2048], bits: &[u32], c: i32) -> bool {
    let Some(&i) = usize::try_from(c >> 5).ok().and_then(|i| index.get(i)) else {
        return false;
    };
    i != 0
        && bits
            .get(usize::from(i))
            .is_some_and(|b| b & (1u32 << (c & 0x1f)) != 0)
}

