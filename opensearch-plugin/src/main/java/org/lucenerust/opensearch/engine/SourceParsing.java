package org.lucenerust.opensearch.engine;

import org.apache.lucene.index.Term;
import org.opensearch.index.VersionType;
import org.opensearch.index.engine.DocumentIndexWriter;
import org.opensearch.index.engine.Engine;
import org.opensearch.index.engine.EngineConfig;
import org.opensearch.index.mapper.DocumentMapperForType;
import org.opensearch.index.mapper.IdFieldMapper;
import org.opensearch.index.mapper.ParsedDocument;
import org.opensearch.index.mapper.SourceToParse;
import org.opensearch.index.mapper.Uid;

import java.io.IOException;
import java.io.UncheckedIOException;

/**
 * An engine's {@link NativeIngest}, there when its index has {@code
 * index.engine.accelerated_source_parsing}. {@code Engine#prepareIndex} asks it first; a null
 * answer leaves the document, whole, to OpenSearch's mapper.
 */
final class SourceParsing {
    private volatile NativeIngest ingest;
    private volatile boolean resolved;

    private NativeIngest ingest(EngineConfig config, DocumentIndexWriter writer) {
        if (resolved == false) {
            synchronized (this) {
                if (resolved == false) {
                    ingest = NativeIngest.SOURCE_PARSING.get(config.getIndexSettings().getSettings())
                        && writer instanceof AcceleratedIndexWriter w ? w.newIngest(config.getIndexSettings()) : null;
                    resolved = true;
                }
            }
        }
        return ingest;
    }

    @SuppressWarnings("deprecation") // DocumentMapperForType is the type Engine#prepareIndex takes
    Engine.Index prepare(
        EngineConfig config,
        DocumentIndexWriter writer,
        DocumentMapperForType docMapper,
        SourceToParse source,
        long seqNo,
        long primaryTerm,
        long version,
        VersionType versionType,
        Engine.Operation.Origin origin,
        long autoGeneratedIdTimestamp,
        boolean isRetry,
        long ifSeqNo,
        long ifPrimaryTerm
    ) {
        NativeIngest ingest = ingest(config, writer);
        if (ingest == null || docMapper.getMapping() != null) {
            return null;
        }
        long startTime = System.nanoTime();
        ParsedDocument doc;
        try {
            doc = ingest.parse(docMapper.getDocumentMapper(), source);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        if (doc == null) {
            return null;
        }
        return new Engine.Index(
            new Term(IdFieldMapper.NAME, Uid.encodeId(doc.id())),
            doc,
            seqNo,
            primaryTerm,
            version,
            versionType,
            origin,
            startTime,
            autoGeneratedIdTimestamp,
            isRetry,
            ifSeqNo,
            ifPrimaryTerm
        );
    }
}
