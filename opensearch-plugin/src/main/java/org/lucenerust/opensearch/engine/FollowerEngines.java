package org.lucenerust.opensearch.engine;

import java.io.IOException;

import org.opensearch.index.engine.EngineConfig;
import org.opensearch.index.engine.InternalEngine;
import org.opensearch.index.seqno.SequenceNumbers;

/**
 * Engines for a cross-cluster replication follower index, when the replication plugin leaves the
 * follower's engine to this plugin ({@code plugins.replication.follower.engine: delegate}).
 *
 * <p>Both behave as the replication plugin's {@code ReplicationEngine}: the follower's primary
 * receives the leader's operations with origin {@code PRIMARY} and their leader sequence numbers,
 * keeps those numbers, plans them as a replica plans (no version checks, no in-flight doc
 * accounting), and never fills sequence-number gaps, since the leader owns the sequence-number space.
 * {@link Accelerated} does so on the accelerated engine, {@link Standard} on OpenSearch's.
 */
public final class FollowerEngines {
    private FollowerEngines() {}

    /** A follower on the accelerated engine. */
    public static final class Accelerated extends RustEngine {
        public Accelerated(EngineConfig config) {
            super(config);
        }

        @Override
        protected boolean assertPrimaryIncomingSequenceNumber(Operation.Origin origin, long seqNo) {
            assert origin == Operation.Origin.PRIMARY : "expected origin PRIMARY for a replicated operation, got " + origin;
            assert seqNo != SequenceNumbers.UNASSIGNED_SEQ_NO : "a replicated operation has no sequence number";
            return true;
        }

        @Override
        protected long generateSeqNoForOperationOnPrimary(Operation operation) {
            return leaderSeqNo(operation);
        }

        @Override
        protected IndexingStrategy indexingStrategyForOperation(Index index) throws IOException {
            return planIndexingAsNonPrimary(asReplica(index));
        }

        @Override
        protected DeletionStrategy deletionStrategyForOperation(Delete delete) throws IOException {
            return planDeletionAsNonPrimary(asReplica(delete));
        }

        @Override
        protected boolean assertNonPrimaryOrigin(Operation operation) {
            return true;
        }

        @Override
        public int fillSeqNoGaps(long primaryTerm) {
            return 0;
        }
    }

    /** A follower on OpenSearch's engine: an index the accelerated engine does not serve. */
    public static final class Standard extends InternalEngine {
        public Standard(EngineConfig config) {
            super(config);
        }

        @Override
        protected boolean assertPrimaryIncomingSequenceNumber(Operation.Origin origin, long seqNo) {
            assert origin == Operation.Origin.PRIMARY : "expected origin PRIMARY for a replicated operation, got " + origin;
            assert seqNo != SequenceNumbers.UNASSIGNED_SEQ_NO : "a replicated operation has no sequence number";
            return true;
        }

        @Override
        protected long generateSeqNoForOperationOnPrimary(Operation operation) {
            return leaderSeqNo(operation);
        }

        @Override
        protected org.opensearch.index.engine.IndexingStrategy indexingStrategyForOperation(Index index) throws IOException {
            return planIndexingAsNonPrimary(asReplica(index));
        }

        @Override
        protected org.opensearch.index.engine.DeletionStrategy deletionStrategyForOperation(Delete delete) throws IOException {
            return planDeletionAsNonPrimary(asReplica(delete));
        }

        @Override
        protected boolean assertNonPrimaryOrigin(Operation operation) {
            return true;
        }

        @Override
        public int fillSeqNoGaps(long primaryTerm) {
            return 0;
        }
    }

    static long leaderSeqNo(org.opensearch.index.engine.Engine.Operation operation) {
        if (operation.seqNo() == SequenceNumbers.UNASSIGNED_SEQ_NO) {
            throw new IllegalStateException("a follower index takes operations with their leader's sequence numbers, and this one has none");
        }
        return operation.seqNo();
    }

    /** {@code index} as a replica receives it: the planners' non-primary path asserts that origin. */
    static org.opensearch.index.engine.Engine.Index asReplica(org.opensearch.index.engine.Engine.Index index) {
        return new org.opensearch.index.engine.Engine.Index(
            index.uid(),
            index.parsedDoc(),
            index.seqNo(),
            index.primaryTerm(),
            index.version(),
            null,
            org.opensearch.index.engine.Engine.Operation.Origin.REPLICA,
            index.startTime(),
            index.getAutoGeneratedIdTimestamp(),
            index.isRetry(),
            SequenceNumbers.UNASSIGNED_SEQ_NO,
            0
        );
    }

    static org.opensearch.index.engine.Engine.Delete asReplica(org.opensearch.index.engine.Engine.Delete delete) {
        return new org.opensearch.index.engine.Engine.Delete(
            delete.id(),
            delete.uid(),
            delete.seqNo(),
            delete.primaryTerm(),
            delete.version(),
            null,
            org.opensearch.index.engine.Engine.Operation.Origin.REPLICA,
            delete.startTime(),
            SequenceNumbers.UNASSIGNED_SEQ_NO,
            0
        );
    }
}
