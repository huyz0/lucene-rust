GENERATED_HEADER = re.compile(r"generated by|do not edit|@generated", re.IGNORECASE)

INCLUDE = re.compile(r'include_(?:bytes|str)!\(\s*"([^"]+)"')


def vendored_dirs():
    """Every directory an include under crates/*/src reads from, with one
    including file as the example."""
    found = {}
    crates = os.path.join(ROOT, "crates")
    for crate in sorted(os.listdir(crates)):
        src = os.path.join(crates, crate, "src")
        for dirpath, _, files in os.walk(src):
            for f in sorted(files):
                if not f.endswith(".rs"):
                    continue
                path = os.path.join(dirpath, f)
                with open(path, encoding="utf-8") as fh:
                    text = fh.read()
                for m in INCLUDE.finditer(text):
                    target = os.path.normpath(os.path.join(dirpath, m.group(1)))
                    d = os.path.relpath(os.path.dirname(target), ROOT)
                    found.setdefault(d, os.path.relpath(path, ROOT))
    return found


def generated_files():
    """Every crates/*/src file whose first 15 lines say it is generated."""
    found = []
    crates = os.path.join(ROOT, "crates")
    for crate in sorted(os.listdir(crates)):
        src = os.path.join(crates, crate, "src")
        for dirpath, _, files in os.walk(src):
            for f in sorted(files):
                if not f.endswith(".rs"):
                    continue
                path = os.path.join(dirpath, f)
                with open(path, encoding="utf-8") as fh:
                    head = "".join(line for _, line in zip(range(15), fh))
                if GENERATED_HEADER.search(head):
                    found.append(os.path.relpath(path, ROOT))
    return found


def generated_entry(path):
    """The GENERATED key covering `path`: the file, or its directory."""
    if path in GENERATED:
        return path
    for key in GENERATED:
        if key.endswith("/") and path.startswith(key):
            return key
    return None


def check_generated(shipped, errors):
    """GENERATED against the tree and the shipped files; the file count."""
    files = generated_files()
    used = set()
    for path in files:
        key = generated_entry(path)
        if key is None:
            errors.append(
                f"{path}: generated, but not in GENERATED -- record whose data it "
                "is and its licence (docs/licences.md), and attribute it in NOTICE"
            )
            continue
        used.add(key)
    for key, (what, attribute, licences) in sorted(GENERATED.items()):
        if key not in used:
            errors.append(f"{key}: in GENERATED but no generated file is there any more -- drop the entry")
        if attribute and key not in shipped["NOTICE"]:
            errors.append(f"{key}: NOTICE does not name it ({what})")
        for name, marker in licences:
            if marker not in shipped[name]:
                errors.append(f"{key}: {name} lacks the licence of {what} (no line {marker!r})")
    return len(files)


def main():
    found = vendored_dirs()
    if "--list" in sys.argv[1:]:
        for d, example in sorted(found.items()):
            print(f"{d}\t(e.g. {example})")
        return 0
    shipped = {}
    for name in ("LICENSE", "NOTICE"):
        with open(os.path.join(ROOT, name), encoding="utf-8") as fh:
            shipped[name] = fh.read()
    errors = []
    for d, example in sorted(found.items()):
        if d not in VENDORED:
            errors.append(
                f"{d}: embedded by {example} but not in VENDORED -- record its "
                "licence here and append its text to LICENSE"
            )
    for d, licences in sorted(VENDORED.items()):
        if d not in found:
            errors.append(f"{d}: in VENDORED but nothing embeds it any more -- drop the entry")
        for what, name, marker in licences:
            if marker not in shipped[name]:
                errors.append(f"{d}: {name} lacks the licence of {what} (no line {marker!r})")
    generated = check_generated(shipped, errors)
    for e in errors:
        print(f"check-vendored-licences: {e}", file=sys.stderr)
    if errors:
        return 1
    print(f"check-vendored-licences: {len(found)} vendored directories and {generated} "
          "generated files, each licence shipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
