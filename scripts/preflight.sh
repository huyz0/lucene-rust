#!/usr/bin/env bash
# Refuses to start a heavy job on a machine that cannot finish it.
#
# Two failures took this project's sessions down, and both were silent until
# the end:
#
#   * Docker Desktop's engine stopped answering. `docker run` then hangs or
#     returns a 500, and every agent waiting on it waits for ever.
#   * The disk filled. Docker Desktop keeps its whole VM in one virtual disk
#     (`docker_data.vhdx`) that grows and never shrinks; it reached 696 GB on a
#     931 GB drive, `C:` had 1.5 GB free, rustc died with SIGBUS mid-build and
#     the engine went down with it. Nothing checked either before the gate ran.
#
# Modes (the first argument):
#
#   host        before `docker run`: the engine answers, the drives holding
#               Docker's disk and this repo have room, the virtual disk is not
#               out of hand, and Docker's build cache stays under its cap.
#   container   at the top of `gate.sh` (also usable natively): the target
#               directory and /tmp have room, and a runaway `incremental`
#               directory is trimmed before it can fill the volume.
#
# A hard limit exits non-zero with what to do about it; a soft one prints a
# warning and carries on. Nothing here deletes data other than Docker's
# *build cache* (reproducible by definition) and cargo's `incremental`
# directories (regenerated by the next build). It never touches volumes,
# images or containers.
#
# Knobs (defaults in parentheses; GB are 1024^3):
#   PREFLIGHT=0                skip every check (CI, where the runner is a VM)
#   MIN_FREE_GB=25             hard floor on the drive holding Docker's disk
#   WARN_FREE_GB=60            warn below this
#   MIN_REPO_FREE_GB=5         hard floor on the drive holding this repo
#   DOCKER_VHDX_MAX_GB=300     ceiling on Docker Desktop's virtual disk: above
#                              it, refuse while its drive has under
#                              VHDX_HARD_FREE_GB (150) free, else warn
#   DOCKER_DATA_PATH=...       where Docker's disk lives (auto-detected)
#   BUILD_CACHE_MAX_GB=40      docker build cache above this is pruned down to
#                              BUILD_CACHE_KEEP_GB (20); DOCKER_AUTO_PRUNE=0
#                              only warns
#   DOCKER_TIMEOUT=30          seconds to wait for the engine
#   MIN_TARGET_FREE_GB=15      (container) hard floor under the target dir
#   TARGET_MAX_GB=60           (container) a target dir above this loses superseded
#                              build artifacts, then llvm-cov-target
#   INCREMENTAL_MAX_MB=20480   (container) incremental dirs above this are cleared
set -euo pipefail

MODE="${1:-host}"
[ "${PREFLIGHT:-1}" = "0" ] && exit 0

MIN_FREE_GB="${MIN_FREE_GB:-25}"
WARN_FREE_GB="${WARN_FREE_GB:-60}"
MIN_REPO_FREE_GB="${MIN_REPO_FREE_GB:-5}"
DOCKER_VHDX_MAX_GB="${DOCKER_VHDX_MAX_GB:-300}"
VHDX_HARD_FREE_GB="${VHDX_HARD_FREE_GB:-150}"
BUILD_CACHE_MAX_GB="${BUILD_CACHE_MAX_GB:-40}"
BUILD_CACHE_KEEP_GB="${BUILD_CACHE_KEEP_GB:-20}"
DOCKER_TIMEOUT="${DOCKER_TIMEOUT:-30}"
MIN_TARGET_FREE_GB="${MIN_TARGET_FREE_GB:-15}"
TARGET_MAX_GB="${TARGET_MAX_GB:-60}"
INCREMENTAL_MAX_MB="${INCREMENTAL_MAX_MB:-20480}"

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

fail() { echo "preflight: FAIL: $*" >&2; exit 1; }
warn() { echo "preflight: warning: $*" >&2; }
note() { echo "preflight: $*" >&2; }

# Free gibibytes on the filesystem holding $1 (integer, rounded down).
free_gb() {
  df -Pk "$1" 2>/dev/null | awk 'NR==2 { printf "%d", $4 / 1048576 }'
}

# Size in gibibytes of the directory tree at $1 (0 if absent).
dir_gb() {
  [ -d "$1" ] || { echo 0; return; }
  du -sk "$1" 2>/dev/null | awk '{ printf "%d", $1 / 1048576 }'
}

# Size in mebibytes of the directory tree at $1 (0 if absent).
dir_mb() {
  [ -d "$1" ] || { echo 0; return; }
  du -sk "$1" 2>/dev/null | awk '{ printf "%d", $1 / 1024 }'
}

host_checks() {
  command -v docker >/dev/null 2>&1 || fail "docker is not installed or not on PATH"

  # 1. The engine answers. Without the timeout a dead engine hangs here for
  #    ever, which is how an agent ends up "waiting on background work".
  if ! timeout "$DOCKER_TIMEOUT" docker version --format '{{.Server.Version}}' >/dev/null 2>&1; then
    fail "the docker engine did not answer within ${DOCKER_TIMEOUT}s.
  Docker Desktop is stopped or wedged. Check free disk space first (a full
  drive is the usual cause), then restart Docker Desktop. Do not start more
  jobs until 'docker version' answers."
  fi

  # 2. Room on the drive holding Docker's disk. Docker Desktop on Windows keeps
  #    it under %LOCALAPPDATA%; elsewhere /var/lib/docker, else $HOME.
  local data="${DOCKER_DATA_PATH:-}"
  if [ -z "$data" ] && [ -n "${LOCALAPPDATA:-}" ] && command -v cygpath >/dev/null 2>&1; then
    data="$(cygpath -u "$LOCALAPPDATA")/Docker"
  fi
  if [ -z "$data" ] || [ ! -d "$data" ]; then
    if [ -d /var/lib/docker ]; then data=/var/lib/docker; else data="$HOME"; fi
  fi

  local free
  free="$(free_gb "$data")"
  [ -n "$free" ] || fail "cannot read free space of $data"
  if [ "$free" -lt "$MIN_FREE_GB" ]; then
    fail "only ${free} GB free where docker keeps its disk ($data); need ${MIN_FREE_GB}.
  A build that fills the drive kills rustc and then the engine. Free space
  first (docker builder prune; compact the virtual disk; delete old
  worktrees' target dirs), or lower MIN_FREE_GB knowingly."
  elif [ "$free" -lt "$WARN_FREE_GB" ]; then
    warn "${free} GB free where docker keeps its disk ($data); below ${WARN_FREE_GB}"
  fi

  # 3. The virtual disk itself. It grows when the VM writes and never shrinks,
  #    so its size is the high-water mark of everything the engine ever held.
  local vhdx
  vhdx="$(find "$data" -maxdepth 4 -name '*.vhdx' -size +1G 2>/dev/null | head -1 || true)"
  if [ -n "$vhdx" ]; then
    local vgb
    vgb="$(du -sk "$vhdx" 2>/dev/null | awk '{ printf "%d", $1 / 1048576 }')"
    if [ "${vgb:-0}" -gt "$DOCKER_VHDX_MAX_GB" ]; then
      local msg="docker's virtual disk is ${vgb} GB (limit ${DOCKER_VHDX_MAX_GB}): $vhdx
  It only grows. Prune with 'docker builder prune' and 'docker image prune',
  then compact it (Docker Desktop > Troubleshoot > Clean / Purge data, or
  'Optimize-VHD -Mode Full' with the engine stopped)."
      # The size is a high-water mark, not a hazard by itself: compacting needs
      # the engine stopped (other projects' containers with it), so an
      # oversized disk on a roomy drive warns and only a drive that could
      # plausibly fill refuses.
      if [ "$free" -lt "$VHDX_HARD_FREE_GB" ]; then
        fail "$msg
  Refusing because the drive has only ${free} GB free (VHDX_HARD_FREE_GB=${VHDX_HARD_FREE_GB})."
      fi
      warn "$msg"
    fi
  fi

  # 4. The repo's own drive (host checkouts, fixtures, benchmark outputs).
  local rfree
  rfree="$(free_gb "$REPO")"
  if [ -n "$rfree" ] && [ "$rfree" -lt "$MIN_REPO_FREE_GB" ]; then
    fail "only ${rfree} GB free on the drive holding $REPO; need ${MIN_REPO_FREE_GB}"
  fi

  # 5. Docker's build cache is the one thing that grows without anybody
  #    asking. Bound it; images and volumes are never touched.
  local cache_gb
  cache_gb="$(timeout "$DOCKER_TIMEOUT" docker system df --format '{{.Type}}={{.Size}}' 2>/dev/null \
    | awk -F= '$1 == "Build Cache" {
        v = $2; u = v; gsub(/[0-9.]/, "", u); gsub(/[A-Za-z]/, "", v);
        if (u == "TB") v *= 1024; else if (u == "MB") v /= 1024;
        else if (u == "kB" || u == "B") v = 0;
        printf "%d", v }' || true)"
  if [ -n "$cache_gb" ] && [ "$cache_gb" -gt "$BUILD_CACHE_MAX_GB" ]; then
    if [ "${DOCKER_AUTO_PRUNE:-1}" = "1" ]; then
      note "docker build cache is ${cache_gb} GB (cap ${BUILD_CACHE_MAX_GB}); pruning to ${BUILD_CACHE_KEEP_GB} GB"
      timeout 600 docker builder prune -f --keep-storage "${BUILD_CACHE_KEEP_GB}GB" >/dev/null 2>&1 \
        || warn "docker builder prune failed"
    else
      warn "docker build cache is ${cache_gb} GB (cap ${BUILD_CACHE_MAX_GB}); run: docker builder prune --keep-storage ${BUILD_CACHE_KEEP_GB}GB"
    fi
  fi

  note "ok (docker answers; ${free} GB free at $data)"
}

# Keeps the target volume under TARGET_MAX_GB. It was found at 147 GB, 123 GB
# of it `llvm-cov-target/debug/deps`: every instrumented test binary (about 70 MB
# each, a few hundred integration tests) is rebuilt under a new hash whenever
# its dependencies change, and cargo never deletes the old ones. Two steps, the
# cheaper first, each only while the target is still over the cap:
#   1. keep only the newest build of each artifact in every `deps` directory
#      (what `cargo sweep` does; older hashes are unreferenced leftovers);
#   2. drop `llvm-cov-target` outright (the next coverage run rebuilds it).
# Only build outputs are removed, and all of them regenerate.
trim_target() {
  local target="$1" size
  size="$(dir_gb "$target")"
  [ "$size" -gt "$TARGET_MAX_GB" ] || { note "target dir is ${size} GB (cap ${TARGET_MAX_GB})"; return 0; }
  note "target dir is ${size} GB (cap ${TARGET_MAX_GB}); removing superseded build artifacts"
  python3 - "$target" <<'PY'
import os, re, sys
newest = {}
doomed = []
hash_re = re.compile(r"^(.*)-([0-9a-f]{16})(\..*)?$")
for root, dirs, files in os.walk(sys.argv[1]):
    if os.path.basename(root) != "deps":
        continue
    dirs[:] = []
    groups = {}
    for name in files:
        m = hash_re.match(name)
        if not m:
            continue
        path = os.path.join(root, name)
        groups.setdefault((m.group(1), m.group(3) or ""), []).append((os.path.getmtime(path), m.group(2), path))
    for entries in groups.values():
        entries.sort(reverse=True)
        keep = entries[0][1]
        doomed += [p for _, h, p in entries if h != keep]
freed = 0
for p in doomed:
    try:
        freed += os.path.getsize(p)
        os.remove(p)
    except OSError:
        pass
print(f"preflight: removed {len(doomed)} superseded artifacts ({freed // 2**30} GB)", file=sys.stderr)
PY
  size="$(dir_gb "$target")"
  if [ "$size" -gt "$TARGET_MAX_GB" ] && [ -d "$target/llvm-cov-target" ]; then
    note "still ${size} GB; removing llvm-cov-target"
    rm -rf "$target/llvm-cov-target"
    size="$(dir_gb "$target")"
  fi
  [ "$size" -gt "$TARGET_MAX_GB" ] && warn "target dir is still ${size} GB (cap ${TARGET_MAX_GB})"
  return 0
}

container_checks() {
  local target="${CARGO_TARGET_DIR:-$REPO/target}"
  mkdir -p "$target" 2>/dev/null || true

  # Incremental compilation state is the part of a target dir that balloons
  # (one copy per crate per profile) and is the cheapest to regenerate.
  local inc
  inc="$(find "$target" -maxdepth 3 -type d -name incremental 2>/dev/null || true)"
  if [ -n "$inc" ]; then
    local total=0 d
    while IFS= read -r d; do
      total=$((total + $(dir_mb "$d")))
    done <<<"$inc"
    if [ "$total" -gt "$INCREMENTAL_MAX_MB" ]; then
      note "incremental dirs hold ${total} MB (cap ${INCREMENTAL_MAX_MB}); clearing them"
      while IFS= read -r d; do rm -rf "$d"; done <<<"$inc"
    fi
  fi

  trim_target "$target"

  local free
  free="$(free_gb "$target")"
  if [ -n "$free" ] && [ "$free" -lt "$MIN_TARGET_FREE_GB" ]; then
    fail "only ${free} GB free under $target; need ${MIN_TARGET_FREE_GB}.
  The target volume is a build cache: 'docker volume rm lucene-rust-target'
  from the host recreates it empty. Do that deliberately, not mid-build."
  fi

  local tfree
  tfree="$(free_gb /tmp)"
  if [ -n "$tfree" ] && [ "$tfree" -lt 1 ]; then
    warn "/tmp has under 1 GB free"
  fi
  note "ok (${free:-?} GB free under $target)"
}

case "$MODE" in
  host) host_checks ;;
  container) container_checks ;;
  *) echo "usage: preflight.sh host|container" >&2; exit 2 ;;
esac
