import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Comparator;
import org.apache.lucene.analysis.core.WhitespaceAnalyzer;
import org.apache.lucene.document.Document;
import org.apache.lucene.document.Field;
import org.apache.lucene.document.FieldType;
import org.apache.lucene.document.StoredField;
import org.apache.lucene.index.IndexOptions;
import org.apache.lucene.index.IndexWriter;
import org.apache.lucene.index.IndexWriterConfig;
import org.apache.lucene.store.FSDirectory;

/**
 * Java side of the indexing-throughput benchmark. The Rust side is
 * {@code benchmarks/rust-runner/src/index_bench.rs}.
 *
 * <p>Same synthetic documents on both sides, generated by the same xorshift over the same
 * vocabulary: a stored string field plus an indexed text field with DOCS_AND_FREQS. The shape is
 * deliberately narrow because this port's IndexWriter has no points or term-vector write path, and
 * benchmarking a document only one engine can write would measure nothing.
 *
 * <p>Emits TSV {@code index<TAB>docs_per_sec<TAB>docs} on stdout.
 */
public final class IndexMicro {

    public static void main(String[] args) throws Exception {
        int nDocs = args.length > 0 ? Integer.parseInt(args[0]) : 50_000;
        Path out = Paths.get(args.length > 1 ? args[1] : "/tmp/lucene-java-index-bench");

        String[] vocab = new String[20_000];
        for (int i = 0; i < vocab.length; i++) vocab[i] = "t" + i;

        String[] bodies = new String[nDocs];
        int state = 0x9E3779B9;
        for (int d = 0; d < nDocs; d++) {
            StringBuilder sb = new StringBuilder(240);
            for (int i = 0; i < 40; i++) {
                state ^= state << 13;
                state ^= state >>> 17;
                state ^= state << 5;
                if (i > 0) sb.append(' ');
                sb.append(vocab[Integer.remainderUnsigned(state, vocab.length)]);
            }
            bodies[d] = sb.toString();
        }

        if (Files.exists(out)) {
            try (var walk = Files.walk(out)) {
                walk.sorted(Comparator.reverseOrder()).forEach(p -> p.toFile().delete());
            }
        }
        Files.createDirectories(out);

        FieldType bodyType = new FieldType();
        bodyType.setIndexOptions(IndexOptions.DOCS_AND_FREQS);
        bodyType.setTokenized(true);
        bodyType.setStored(false);
        bodyType.freeze();

        long start;
        try (FSDirectory dir = FSDirectory.open(out);
             IndexWriter w = new IndexWriter(dir, new IndexWriterConfig(new WhitespaceAnalyzer()))) {
            start = System.nanoTime();
            for (int d = 0; d < nDocs; d++) {
                Document doc = new Document();
                doc.add(new StoredField("id", "doc" + d));
                doc.add(new Field("body", bodies[d], bodyType));
                w.addDocument(doc);
            }
            w.commit();
        }
        double ns = System.nanoTime() - start;
        // Nanoseconds per document -- same units as index_bench.rs on the Rust side.
        System.out.printf("index\t%.3f\t%d%n", ns / nDocs, nDocs);
    }
}
