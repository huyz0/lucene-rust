  static String run(Scenario s) throws Exception {
    try (Directory dir = new ByteBuffersDirectory()) {
      SegmentInfos infos = new SegmentInfos(Version.LATEST.major);
      Map<String, SegmentCommitInfo> byName = new LinkedHashMap<>();
      for (Seg seg : s.segments) {
        SegmentCommitInfo sci = commitInfo(dir, seg);
        infos.add(sci);
        byName.put(seg.name, sci);
      }
      Set<SegmentCommitInfo> merging = new LinkedHashSet<>();
      for (String n : s.merging) merging.add(byName.get(n));
      MergePolicy.MergeContext ctx = context(merging);
      MergePolicy policy = build(s.policy, s.ranges, byName);
      String op = s.op;
      if (op.startsWith("useCompoundFile:")) {
        return Boolean.toString(
            policy.useCompoundFile(infos, byName.get(op.substring(16)), ctx));
      }
      MergePolicy.MergeSpecification spec;
      boolean sortGroups = false;
      if (op.equals("findMerges")) {
        spec = policy.findMerges(MergeTrigger.EXPLICIT, infos, ctx);
      } else if (op.equals("findFullFlushMerges")) {
        spec = policy.findFullFlushMerges(MergeTrigger.FULL_FLUSH, infos, ctx);
      } else if (op.startsWith("findForcedMerges:")) {
        Map<SegmentCommitInfo, Boolean> toMerge = new HashMap<>();
        for (Map.Entry<String, Boolean> e : s.toMerge.entrySet()) {
          toMerge.put(byName.get(e.getKey()), e.getValue());
        }
        spec = policy.findForcedMerges(infos, Integer.parseInt(op.substring(17)), toMerge, ctx);
        sortGroups = s.policy.startsWith("temporal");
      } else if (op.equals("findForcedDeletesMerges")) {
        spec = policy.findForcedDeletesMerges(infos, ctx);
      } else {
        throw new IllegalArgumentException(op);
      }
      return render(spec, sortGroups);
    }
  }

  static String render(MergePolicy.MergeSpecification spec, boolean sortGroups) {
    if (spec == null) return "null";
    List<String> groups = new ArrayList<>();
    for (MergePolicy.OneMerge m : spec.merges) {
      List<String> names = new ArrayList<>();
      for (SegmentCommitInfo sci : m.segments) names.add(sci.info.name);
      if (sortGroups) Collections.sort(names);
      groups.add(String.join(",", names));
    }
    if (sortGroups) Collections.sort(groups);
    return String.join("|", groups);
  }

  static MergePolicy.MergeContext context(Set<SegmentCommitInfo> merging) {
    return new MergePolicy.MergeContext() {
      @Override
      public int numDeletesToMerge(SegmentCommitInfo info) {
        return info.getDelCount();
      }

      @Override
      public int numDeletedDocs(SegmentCommitInfo info) {
        return info.getDelCount();
      }

      @Override
      public InfoStream getInfoStream() {
        return InfoStream.NO_OUTPUT;
      }

      @Override
      public Set<SegmentCommitInfo> getMergingSegments() {
        return Collections.unmodifiableSet(merging);
      }
    };
  }

  /** As in GenMergePolicy: {@code sizeInBytes()} is the length of one real file. */
  static SegmentCommitInfo commitInfo(Directory dir, Seg seg) throws IOException {
    String fileName = seg.name + ".dat";
    try (IndexOutput o = dir.createOutput(fileName, IOContext.DEFAULT)) {
      byte[] chunk = new byte[1024];
      long remaining = seg.bytes;
      while (remaining > 0) {
        int n = (int) Math.min(chunk.length, remaining);
        o.writeBytes(chunk, 0, n);
        remaining -= n;
      }
    }
    byte[] id = new byte[StringHelper.ID_LENGTH];
    for (int i = 0; i < id.length; i++) {
      id[i] = (byte) (seg.name.hashCode() >>> (i % 4) * 8);
    }
    SegmentInfo info =
        new SegmentInfo(
            dir,
            Version.LATEST,
            Version.LATEST,
            seg.name,
            seg.maxDoc,
            seg.cfs,
            false,
            Codec.getDefault(),
            Map.of(),
            id,
            Map.of(),
            null);
    info.setFiles(Set.of(fileName));
    return new SegmentCommitInfo(info, seg.delCount, 0, -1, -1, -1, id);
  }

