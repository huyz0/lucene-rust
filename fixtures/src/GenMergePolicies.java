  /**
   * One segment per flush, each with LongPoint("ts") values inside one hour of the far future
   * (milliseconds), plus a seconds-unit segment and a segment without the field; the policy reads
   * the ranges from the points itself.
   */
  static void temporalIndex(Path dir) throws Exception {
    if (Files.exists(dir)) {
      try (var files = Files.list(dir)) {
        for (Path f : (Iterable<Path>) files::iterator) Files.delete(f);
      }
    }
    Files.createDirectories(dir);
    try (Directory d = FSDirectory.open(dir)) {
      IndexWriterConfig cfg = new IndexWriterConfig();
      cfg.setMergePolicy(NoMergePolicy.INSTANCE);
      cfg.setUseCompoundFile(false);
      try (IndexWriter w = new IndexWriter(d, cfg)) {
        // hour 0: 5 segments; hour 1: 3 segments; hour 3: 4 segments, one in seconds.
        long[][] segs = {
          {FUTURE, FUTURE + 10}, {FUTURE + 20, FUTURE + 30, FUTURE + 31}, {FUTURE + 40},
          {FUTURE + 50, FUTURE + 55}, {FUTURE + 60, FUTURE + 61, FUTURE + 62, FUTURE + 63},
          {FUTURE + HOUR + 1}, {FUTURE + HOUR + 2, FUTURE + HOUR + 3}, {FUTURE + HOUR + 9},
          {FUTURE + 3 * HOUR}, {FUTURE + 3 * HOUR + 5}, {FUTURE + 3 * HOUR + 6},
        };
        for (int i = 0; i < segs.length; i++) {
          // Alternate compound segments, so the date range is read through .cfs too.
          w.getConfig().setUseCompoundFile(i % 3 == 1);
          for (long ts : segs[i]) {
            Document doc = new Document();
            doc.add(new LongPoint("ts", ts));
            doc.add(new StoredField("v", ts));
            w.addDocument(doc);
          }
          w.flush();
        }
        // Seconds since the epoch, same window as hour 3.
        Document doc = new Document();
        doc.add(new LongPoint("ts", (FUTURE + 3 * HOUR + 7) / 1000));
        w.addDocument(doc);
        w.flush();
        // No temporal field at all: never bucketed.
        doc = new Document();
        doc.add(new StoredField("v", 1L));
        w.addDocument(doc);
        w.flush();
        w.commit();
      }
      SegmentInfos infos = SegmentInfos.readLatestCommit(d);
      StringBuilder sb = new StringBuilder();
      sb.append("# Generated by fixtures/src/GenMergePolicies.java against Lucene ")
          .append(Version.LATEST)
          .append('\n');
      sb.append("# TemporalMergePolicy over this index, date ranges read from the segments.\n");
      sb.append("segments=");
      List<String> names = new ArrayList<>();
      for (SegmentCommitInfo sci : infos) names.add(sci.info.name + ":" + sci.info.maxDoc());
      sb.append(String.join(",", names)).append('\n');
      String[][] cases = {
        {"natural", "temporal;exponential=false", "findMerges"},
        {"natural_min3", "temporal;exponential=false;minThreshold=3", "findMerges"},
        {"natural_exponential", "temporal", "findMerges"},
        {"forced_one", "temporal;exponential=false", "findForcedMerges:1"},
      };
      Set<SegmentCommitInfo> none = Set.of();
      for (String[] c : cases) {
        MergePolicy p = build(c[1], null, null);
        MergePolicy.MergeSpecification spec;
        boolean sort = false;
        if (c[2].equals("findMerges")) {
          spec = p.findMerges(MergeTrigger.EXPLICIT, infos, context(none));
        } else {
          Map<SegmentCommitInfo, Boolean> toMerge = new HashMap<>();
          for (SegmentCommitInfo sci : infos) toMerge.put(sci, true);
          spec = p.findForcedMerges(infos, 1, toMerge, context(none));
          sort = true;
        }
        sb.append("case.").append(c[0]).append(".policy=").append(c[1]).append('\n');
        sb.append("case.").append(c[0]).append(".op=").append(c[2]).append('\n');
        sb.append("case.").append(c[0]).append(".expected=").append(render(spec, sort)).append('\n');
      }
      Files.writeString(dir.resolve("manifest.properties"), sb.toString(), StandardCharsets.UTF_8);
    }
  }
