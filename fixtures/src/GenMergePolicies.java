  static MergePolicy build(String spec, Map<String, long[]> ranges, Map<String, SegmentCommitInfo> byName)
      throws Exception {
    String[] parts = spec.split(";");
    Map<String, String> kv = new HashMap<>();
    for (int i = 1; i < parts.length; i++) {
      String[] e = parts[i].split("=", 2);
      kv.put(e[0], e[1]);
    }
    switch (parts[0]) {
      case "logbyte":
        {
          LogByteSizeMergePolicy p = new LogByteSizeMergePolicy();
          log(p, kv);
          if (kv.containsKey("minBytes")) p.setMinMergeMB(mb(kv.get("minBytes")));
          if (kv.containsKey("maxBytes")) p.setMaxMergeMB(mb(kv.get("maxBytes")));
          if (kv.containsKey("maxForcedBytes"))
            p.setMaxMergeMBForForcedMerge(mb(kv.get("maxForcedBytes")));
          return p;
        }
      case "logdoc":
        {
          LogDocMergePolicy p = new LogDocMergePolicy();
          log(p, kv);
          if (kv.containsKey("minDocs")) p.setMinMergeDocs(Integer.parseInt(kv.get("minDocs")));
          return p;
        }
      case "tiered":
        {
          TieredMergePolicy p = new TieredMergePolicy();
          if (kv.containsKey("maxMergedBytes"))
            p.setMaxMergedSegmentMB(mb(kv.get("maxMergedBytes")));
          if (kv.containsKey("floorBytes")) p.setFloorSegmentMB(mb(kv.get("floorBytes")));
          if (kv.containsKey("segsPerTier"))
            p.setSegmentsPerTier(Double.parseDouble(kv.get("segsPerTier")));
          if (kv.containsKey("noCFSRatio"))
            p.setNoCFSRatio(Double.parseDouble(kv.get("noCFSRatio")));
          if (kv.containsKey("maxCFSBytes")) p.setMaxCFSSegmentSizeMB(mb(kv.get("maxCFSBytes")));
          return p;
        }
      case "filter":
        {
          // A FilterMergePolicy over a LogDocMergePolicy built from the rest of the spec.
          LogDocMergePolicy inner = new LogDocMergePolicy();
          log(inner, kv);
          if (kv.containsKey("minDocs")) inner.setMinMergeDocs(Integer.parseInt(kv.get("minDocs")));
          return new FilterMergePolicy(inner);
        }
      case "wrapreverse":
        {
          // OneMergeWrappingMergePolicy reversing each merge's segment order.
          LogDocMergePolicy inner = new LogDocMergePolicy();
          log(inner, kv);
          if (kv.containsKey("minDocs")) inner.setMinMergeDocs(Integer.parseInt(kv.get("minDocs")));
          return new OneMergeWrappingMergePolicy(
              inner,
              m -> {
                List<SegmentCommitInfo> l = new ArrayList<>(m.segments);
                Collections.reverse(l);
                return new MergePolicy.OneMerge(l);
              });
        }
      case "temporal":
        {
          TemporalMergePolicy p = new TemporalMergePolicy().setTemporalField("ts");
          // minThreshold first: it may only shrink below the default maxThreshold.
          if (kv.containsKey("minThreshold"))
            p.setMinThreshold(Integer.parseInt(kv.get("minThreshold")));
          if (kv.containsKey("maxThreshold"))
            p.setMaxThreshold(Integer.parseInt(kv.get("maxThreshold")));
          if (kv.containsKey("baseTime")) p.setBaseTimeInSeconds(Long.parseLong(kv.get("baseTime")));
          if (kv.containsKey("maxWindow"))
            p.setMaxWindowSizeSeconds(Long.parseLong(kv.get("maxWindow")));
          if (kv.containsKey("maxAge")) p.setMaxAgeSeconds(Long.parseLong(kv.get("maxAge")));
          if (kv.containsKey("ratio")) p.setCompactionRatio(Double.parseDouble(kv.get("ratio")));
          if (kv.containsKey("forceDeletesPct"))
            p.setForceMergeDeletesPctAllowed(Double.parseDouble(kv.get("forceDeletesPct")));
          if ("false".equals(kv.get("exponential"))) p.disableExponentialBuckets();
          if (ranges != null) {
            // Package-private: TemporalMergePolicy.setSegmentDateRangeOverrides(Map).
            Class<?> rangeClass =
                Class.forName("org.apache.lucene.index.TemporalMergePolicy$SegmentDateRange");
            Constructor<?> ctor = rangeClass.getDeclaredConstructor(long.class, long.class);
            ctor.setAccessible(true);
            Map<SegmentCommitInfo, Object> overrides = new HashMap<>();
            for (Map.Entry<String, long[]> e : ranges.entrySet()) {
              overrides.put(byName.get(e.getKey()), ctor.newInstance(e.getValue()[0], e.getValue()[1]));
            }
            Method m =
                TemporalMergePolicy.class.getDeclaredMethod("setSegmentDateRangeOverrides", Map.class);
            m.setAccessible(true);
            m.invoke(p, overrides);
          }
          return p;
        }
      default:
        throw new IllegalArgumentException(parts[0]);
    }
  }

